"""Write a normalised mesh as a Gazebo model directory with provenance.

Layout (matches the repo's models/ convention, model://NAME/...):
  NAME/model.config
  NAME/model.sdf
  NAME/meshes/<original visual file(s), copied byte-for-byte>
  NAME/meshes/collision.stl   (mesh / convex_hull collision modes)
  NAME/asset_manifest.json    source hashes, transform, checks, assumptions

The visual mesh is never re-exported: the original file (and its textures)
is copied unchanged and the normalising transform is expressed as the SDF
visual <pose> and <scale>. That keeps textures intact and makes the
provenance hash meaningful.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

# Self-contained formats are copied alone; the others may reference sibling
# files (textures, .mtl, .bin), so their whole source directory is copied.
SELF_CONTAINED = {".glb", ".stl"}
MANIFEST = "asset_manifest.json"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _fmt(values):
    return " ".join(f"{v:.6g}" for v in values)


def model_sdf(name, result, visual_file, static):
    sdf = ET.Element("sdf", version="1.9")
    model = ET.SubElement(sdf, "model", name=name)
    ET.SubElement(model, "static").text = "true" if static else "false"
    link = ET.SubElement(model, "link", name="body")
    if result.inertial is not None:
        inertial = ET.SubElement(link, "inertial")
        ET.SubElement(inertial, "pose").text = _fmt(result.inertial["center_of_mass"] + [0, 0, 0])
        ET.SubElement(inertial, "mass").text = f"{result.inertial['mass_kg']:.6g}"
        tensor = ET.SubElement(inertial, "inertia")
        i = result.inertial["inertia"]
        for tag, value in (("ixx", i[0][0]), ("ixy", i[0][1]), ("ixz", i[0][2]),
                           ("iyy", i[1][1]), ("iyz", i[1][2]), ("izz", i[2][2])):
            ET.SubElement(tensor, tag).text = f"{value:.6g}"
    collision = ET.SubElement(link, "collision", name="collision")
    geometry = ET.SubElement(collision, "geometry")
    if result.collision_box is not None:
        size, centre = result.collision_box
        ET.SubElement(collision, "pose").text = _fmt(list(centre) + [0, 0, 0])
        ET.SubElement(ET.SubElement(geometry, "box"), "size").text = _fmt(size)
    else:
        mesh = ET.SubElement(geometry, "mesh")
        ET.SubElement(mesh, "uri").text = f"model://{name}/meshes/collision.stl"
    visual = ET.SubElement(link, "visual", name="visual")
    ET.SubElement(visual, "pose").text = _fmt(list(result.translation) + list(result.visual_rpy))
    vmesh = ET.SubElement(ET.SubElement(visual, "geometry"), "mesh")
    ET.SubElement(vmesh, "uri").text = f"model://{name}/meshes/{visual_file}"
    ET.SubElement(vmesh, "scale").text = _fmt([result.scale] * 3)
    ET.indent(sdf, space="  ")
    return ET.tostring(sdf, encoding="unicode", xml_declaration=True) + "\n"


def model_config(name, description):
    root = ET.Element("model")
    ET.SubElement(root, "name").text = name
    ET.SubElement(root, "version").text = "1.0"
    ET.SubElement(root, "sdf", version="1.9").text = "model.sdf"
    ET.SubElement(root, "description").text = description
    ET.indent(root, space="  ")
    return ET.tostring(root, encoding="unicode", xml_declaration=True) + "\n"


def write_model(out_root, source, spec, result, provenance, overwrite=False):
    """Write the model directory; return the manifest dict."""
    source = Path(source)
    model_dir = Path(out_root) / spec.name
    if model_dir.exists():
        if not overwrite:
            raise FileExistsError(f"{model_dir} exists (pass overwrite=True)")
        if not (model_dir / MANIFEST).is_file():
            raise FileExistsError(f"{model_dir} is not a generated model; refusing to replace it")
        shutil.rmtree(model_dir)
    meshes = model_dir / "meshes"
    meshes.mkdir(parents=True)

    if source.suffix.lower() in SELF_CONTAINED:
        copied = [source]
    else:
        copied = sorted(p for p in source.parent.iterdir() if p.is_file())
    source_files = {}
    for path in copied:
        shutil.copy2(path, meshes / path.name)
        source_files[path.name] = sha256(path)
    if result.collision_mesh is not None:
        result.collision_mesh.export(meshes / "collision.stl")

    description = provenance.get("description") or f"{spec.name} (generated by tools/sim_asset.py)"
    (model_dir / "model.config").write_text(model_config(spec.name, description), encoding="utf-8")
    (model_dir / "model.sdf").write_text(
        model_sdf(spec.name, result, source.name, spec.static), encoding="utf-8")

    manifest = {
        "format": "sim-asset-manifest",
        "version": 1,
        "name": spec.name,
        "created_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "provenance": provenance,
        "source_file": source.name,
        "source_sha256": source_files,
        "import_spec": {k: getattr(spec, k) for k in spec.__dataclass_fields__},
        "transform": {
            "rotation": result.rotation.tolist(),
            "visual_rpy": list(result.visual_rpy),
            "scale": result.scale,
            "translation": result.translation.tolist(),
            "scale_basis": ("target_size_m (unmeasured source; size is an input, not a measurement)"
                            if spec.target_size_m is not None else "source_unit_m (stated units)"),
        },
        "footprint_radius_m": float((result.mesh.extents[:2] ** 2).sum() ** 0.5 / 2),
        "extents_m": result.mesh.extents.tolist(),
        "collision": spec.collision,
        "checks": result.checks,
        "inertial": result.inertial,
        "warnings": result.warnings,
    }
    (model_dir / MANIFEST).write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest
